#!/usr/bin/env python3
"""Generate CoreMark report strings from the actual build options."""

import argparse
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', required=True)
    parser.add_argument('--cflags', required=True)
    parser.add_argument('--ldflags', required=True)
    parser.add_argument('--libs', required=True)
    parser.add_argument('--libc', required=True)
    args = parser.parse_args()
    values = {
        'FLAGS_STR': args.cflags,
        'LINKER_FLAGS_STR': args.ldflags,
        'LINK_LIBS_STR': args.libs,
        'LIBC_NAME_STR': args.libc,
    }
    lines = [
        '/* Generated by scripts/gen_build_info.py; do not edit. */',
        '#ifndef COREMARK_BUILD_INFO_H',
        '#define COREMARK_BUILD_INFO_H',
    ]
    for name, value in values.items():
        lines.append('#define {} {}'.format(name, json.dumps(value, ensure_ascii=True)))
    lines.extend(['#endif', ''])
    content = '\n'.join(lines).encode('ascii')
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    # Keep the timestamp unchanged when options match, for incremental make builds.
    if not output.exists() or output.read_bytes() != content:
        output.write_bytes(content)


if __name__ == '__main__':
    main()
